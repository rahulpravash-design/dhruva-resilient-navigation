"""docs/RESULTS.md from cases.jsonl. Deterministic: no timestamps, fixed ordering, fixed rounding."""
import json
from pathlib import Path

import numpy as np

from ..metrics import summarize

ORDER = ("baseline", "physics", "nhc", "ml", "integrity")
NAMES = {"baseline": "Baseline (gyro heading, held GNSS speed)", "physics": "EKF, physics only",
         "nhc": "+ NHC", "ml": "+ SpeedNet", "integrity": "+ integrity monitor (full pipeline)"}
NM = "— NOT MEASURED"


def read_cases(path):
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line]


def _vals(cases, key):
    return [np.nan if c["metrics"].get(key) is None else c["metrics"][key] for c in cases]


def _f(x, nd=1):
    return "—" if x is None or not np.isfinite(x) else f"{x:.{nd}f}"


def _med_p90(cases, key, nd=1):
    s = summarize(_vals(cases, key))
    return f"{_f(s['median'], nd)} / {_f(s['p90'], nd)}"


def _ablations(cases):
    present = {c["ablation"] for c in cases}
    return [a for a in ORDER if a in present]


def _outage_table(cases, length):
    header = ("| Ablation | n | Endpoint error m (median / p90) | Drift % (median / p90) "
              "| Error per km m (median / p90) | 95 % coverage % (median) | PS pass "
              "| Re-entry jump m (median / p90) | Time to DR mode s (median) |")
    rows = [header, "|---|---|---|---|---|---|---|---|---|"]
    for ab in _ablations(cases):
        sel = [c for c in cases if c["ablation"] == ab and c["outage_s"] == length]
        if not sel:
            continue
        ok = [bool(c["metrics"]["ps_pass"]) for c in sel]
        cov = summarize(_vals(sel, "coverage_pct"))["median"]
        ttd = summarize(_vals(sel, "time_to_detect_s"))["median"]
        rows.append(f"| {NAMES[ab]} | {len(sel)} | {_med_p90(sel, 'endpoint_err_m')} | {_med_p90(sel, 'drift_pct')} "
                    f"| {_med_p90(sel, 'err_per_km_m')} | {_f(cov)} | {sum(ok)}/{len(ok)} ({100 * np.mean(ok):.0f} %) "
                    f"| {_med_p90(sel, 'reentry_jump_m')} | {_f(ttd)} |")
    rows.append("| + map matching | — NOT MEASURED | — | — | — | — | — | — | — |")
    return "\n".join(rows)


def _attack_table(cases, attack):
    header = ("| Ablation | n | Detected | Time to detect s (median / p90) "
              "| Max error after spoof start m (median / p90) | Final error m (median) |")
    rows = [header, "|---|---|---|---|---|---|"]
    for ab in _ablations(cases):
        sel = [c for c in cases if c["ablation"] == ab and c["attack"] == attack]
        if not sel:
            continue
        if ab == "integrity":
            det = f"{sum(c['metrics']['detected'] for c in sel)}/{len(sel)}"
            ttd = _med_p90(sel, "time_to_detect_s")
        else:
            det, ttd = "— (no monitor)", "—"
        final = summarize(_vals(sel, "final_err_m"))["median"]
        rows.append(f"| {NAMES[ab]} | {len(sel)} | {det} | {ttd} | {_med_p90(sel, 'max_err_after_m')} | {_f(final)} |")
    return "\n".join(rows)


def _false_alarms(cases):
    sel = [c for c in cases if c["ablation"] == "integrity"]
    hours = sum(c["metrics"]["clean_s"] for c in sel) / 3600.0
    n = sum(c["metrics"]["false_alarms"] for c in sel)
    return n, hours


def render(cases, summary, ev):
    lengths = sorted({c["outage_s"] for c in cases if c["outage_s"] is not None})
    a = ev["attack"]
    n_fa, hours = _false_alarms(cases)
    fa_rate = _f(n_fa / hours if hours else float("nan"), 1)
    out = []
    add = out.append
    add("# DHRUVA results\n")
    cfg = ev.get("_config", "configs/eval.yaml")
    add(f"Generated by `python -m dhruva.eval --config {cfg}`. Do not edit by hand. "
        f"Every number below is computed from `runs/{ev['id']}/cases.jsonl`.\n")
    add("> **All numbers on this page are SYNTHETIC.** They come from a simulator with an *assumed* phone IMU/GNSS "
        "model and an *assumed* speed-dependent vibration model (`docs/SPEEDNET_ASSUMPTIONS.md`). They show how the "
        "engine behaves in that model. They are not evidence of real-world accuracy.\n")
    add("## Provenance\n")
    add("| Item | Value |\n|---|---|")
    add(f"| Data | {summary['label']}, {summary['grade']}-grade sensors, `{summary['split']}` split "
        f"(trajectory-level, never tuned on), {summary['trajectories']} drives |")
    add(f"| Cases | {summary['cases']} engine runs |")
    add(f"| `cases.jsonl` SHA-256 | `{summary['cases_sha256']}` |")
    add(f"| `{cfg}` SHA-256 | `{summary['eval_yaml_sha256']}` |")
    add(f"| `configs/engine.json` SHA-256 | `{summary['engine_json_sha256']}` |\n")
    add("PS benchmark: drift <= 10 % of distance AND error <= 100 m per km. \"PS pass\" is the number of outage "
        "windows meeting both; it is a synthetic pass rate, not a certification.\n")
    add(f"## 1. Phone-grade, SYNTHETIC, without map matching ({ev['windows_per_trajectory']} random outage windows "
        "per trajectory)\n")
    for length in lengths:
        add(f"### {length} s outage\n\n{_outage_table(cases, length)}\n")
    add(f"## 2. With map matching\n\n{NM}. The synthetic drives are not on a road network, so no map-matched "
        "number exists. The map matcher and router are tested on synthetic graphs only (`test_map_route.py`).\n")
    add(f"## 3. Vehicle-grade sensors\n\n{NM}. No vehicle-grade dataset is available. Phone-grade and "
        "vehicle-grade results are never mixed in one table.\n")
    add(f"## 4. Real datasets and own drives\n\n{NM}. `data/raw/` is empty (`docs/DATA_STATUS.md`).\n")
    add("## 5. Spoofing (SYNTHETIC)\n")
    add(f"Attack starts at a seeded time in {a['start_range_s'][0]:.0f}-{a['start_range_s'][1]:.0f} s. "
        f"Step: {a['step_m']:.0f} m offset east. Ramp: {a['ramp_mps']:.1f} m/s drift east. "
        "The injector shifts the reported position only; the reported Doppler speed and course are left unchanged.\n")
    for attack, title in (("step", "Step spoof"), ("ramp", "Ramp spoof")):
        add(f"### {title}\n\n{_attack_table(cases, attack)}\n")
    add("### False alarms\n\nIntegrity ablation, clean data only (all outage runs and the pre-spoof part of attack "
        f"runs): {n_fa} spoof rejections in {hours:.2f} h of clean data = {fa_rate} per hour.\n")
    add("## 6. How to read this\n")
    add("- Ablations are cumulative: each row adds one component to the row above.")
    add("- Re-entry jump is the largest displayed step beyond expected motion (speed x dt) in the 3 s after GNSS "
        "returns.")
    add("- Coverage is the share of outage epochs whose true error is inside the filter's own 95 % ellipse radius "
        "(target about 95 %). The baseline has no covariance, so it shows —.")
    add("- Known limits are listed in `docs/BLOCKERS.md`; the integrity thresholds were tuned on the `val` split only.")
    return "\n".join(out) + "\n"
